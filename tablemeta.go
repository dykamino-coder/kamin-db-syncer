package main

// Table metadata: columns, primary key, type mapping between SQL Server, FOR JSON and OPENJSON.

import (
	"context"
	"database/sql"
	"fmt"
	"strings"
)

type colMeta struct {
	Name      string
	Type      string
	MaxLen    int
	Prec      int
	Scale     int
	Identity  bool
	PKOrd     int
	Collation string
	Nullable  bool
}

type tableMeta struct {
	Schema, Name string
	Cols         []colMeta // copyable columns (no computed / rowversion), in column order
	PK           []int     // indexes into Cols, in key order
	HasIdentity  bool
	HasTriggers  bool
	RowVersion   string // rowversion column, enables the no-hash "unchanged" fast path
	IntPK        bool   // single-column integer primary key
	RawKey       bool   // PK packs losslessly into 16 bytes: carried whole in the IBLT cells
}

func (c colMeta) decl() string {
	switch c.Type {
	case "varchar", "char", "varbinary", "binary":
		if c.MaxLen == -1 {
			return c.Type + "(max)"
		}
		return fmt.Sprintf("%s(%d)", c.Type, c.MaxLen)
	case "nvarchar", "nchar":
		if c.MaxLen == -1 {
			return c.Type + "(max)"
		}
		return fmt.Sprintf("%s(%d)", c.Type, c.MaxLen/2)
	case "decimal", "numeric":
		return fmt.Sprintf("%s(%d,%d)", c.Type, c.Prec, c.Scale)
	case "datetime2", "time", "datetimeoffset":
		return fmt.Sprintf("%s(%d)", c.Type, c.Scale)
	}
	return c.Type
}

func (c colMeta) kind() string {
	switch c.Type {
	case "binary", "varbinary", "image", "geography", "geometry", "hierarchyid":
		return "bin"
	case "float", "real":
		return "float"
	case "money", "smallmoney":
		return "money"
	case "date", "time", "datetime", "datetime2", "smalldatetime", "datetimeoffset":
		return "time"
	case "char", "varchar", "nchar", "nvarchar", "text", "ntext", "xml":
		return "text"
	}
	return "plain"
}

var supportedPlain = map[string]bool{"bit": true, "tinyint": true, "smallint": true, "int": true, "bigint": true,
	"decimal": true, "numeric": true, "uniqueidentifier": true}

var fixedTypes = map[string]bool{"bit": true, "tinyint": true, "smallint": true, "int": true, "bigint": true,
	"decimal": true, "numeric": true, "money": true, "smallmoney": true, "float": true, "real": true,
	"date": true, "time": true, "datetime": true, "datetime2": true, "smalldatetime": true,
	"datetimeoffset": true, "uniqueidentifier": true}

// srcEnc: value as put into FOR JSON. withType: OPENJSON WITH type. insExpr: back to column type.
func (c colMeta) srcEnc(ref string) string {
	switch {
	case c.kind() == "bin":
		return "CAST(" + ref + " AS varbinary(max))" // FOR JSON emits base64
	case c.kind() == "float":
		return "CONVERT(varchar(40), " + ref + ", 3)"
	case c.Type == "xml" || c.Type == "ntext":
		return "CAST(" + ref + " AS nvarchar(max))"
	case c.Type == "text":
		return "CAST(" + ref + " AS varchar(max))"
	}
	return ref
}

func (c colMeta) withType() string {
	switch {
	case c.kind() == "bin":
		return "varbinary(max)" // OPENJSON decodes base64
	case c.kind() == "float":
		return "varchar(40)"
	case c.Type == "xml" || c.Type == "ntext":
		return "nvarchar(max)"
	case c.Type == "text":
		return "varchar(max)"
	}
	return c.decl()
}

func (c colMeta) insExpr(ref string) string {
	switch c.Type {
	case "float", "real", "geography", "geometry", "hierarchyid", "xml":
		return "CAST(" + ref + " AS " + c.decl() + ")"
	}
	return ref
}

func loadMeta(ctx context.Context, db *sql.DB, schema, name string) (*tableMeta, error) {
	obj := qi(schema) + "." + qi(name)
	rows, err := db.QueryContext(ctx, `
SELECT c.name,
       CASE WHEN t.is_user_defined = 1 AND t.is_assembly_type = 0 THEN TYPE_NAME(c.system_type_id) ELSE t.name END,
       c.max_length, c.precision, c.scale, c.is_identity, c.is_computed, ISNULL(ic.key_ordinal, 0),
       ISNULL(c.collation_name, ''), c.is_nullable
FROM sys.columns c
JOIN sys.types t ON t.user_type_id = c.user_type_id
LEFT JOIN sys.indexes i ON i.object_id = c.object_id AND i.is_primary_key = 1
LEFT JOIN sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id AND ic.column_id = c.column_id
WHERE c.object_id = OBJECT_ID(@t)
ORDER BY c.column_id`, sql.Named("t", obj))
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	m := &tableMeta{Schema: schema, Name: name}
	pk := map[int]int{}
	for rows.Next() {
		var c colMeta
		var computed bool
		if err := rows.Scan(&c.Name, &c.Type, &c.MaxLen, &c.Prec, &c.Scale, &c.Identity, &computed, &c.PKOrd, &c.Collation, &c.Nullable); err != nil {
			return nil, err
		}
		if c.Type == "timestamp" {
			m.RowVersion = c.Name
			continue // generated by the target itself
		}
		if computed {
			continue
		}
		k := c.kind()
		if k == "plain" && !supportedPlain[c.Type] {
			return nil, fmt.Errorf("%s: column %s of type %s is not supported", obj, c.Name, c.Type)
		}
		if c.PKOrd > 0 {
			pk[c.PKOrd] = len(m.Cols)
		}
		m.HasIdentity = m.HasIdentity || c.Identity
		m.Cols = append(m.Cols, c)
	}
	if err := rows.Err(); err != nil {
		return nil, err
	}
	if len(m.Cols) == 0 {
		return nil, fmt.Errorf("table %s not found", obj)
	}
	for i := 1; i <= len(pk); i++ {
		m.PK = append(m.PK, pk[i])
	}
	if len(m.PK) == 1 {
		switch m.Cols[m.PK[0]].Type {
		case "tinyint", "smallint", "int", "bigint":
			m.IntPK = true
		}
	}
	if !m.IntPK && len(m.PK) > 0 {
		n := 0
		for _, i := range m.PK {
			b, ok := m.Cols[i].rawKeyBytes()
			if !ok {
				n = 1 << 20
			}
			n += b
		}
		m.RawKey = n <= 16
	}
	var trg int
	if err := db.QueryRowContext(ctx, `SELECT COUNT(*) FROM sys.triggers WHERE parent_id = OBJECT_ID(@t)`,
		sql.Named("t", obj)).Scan(&trg); err != nil {
		return nil, err
	}
	m.HasTriggers = trg > 0
	return m, nil
}

func checkSameColumns(src, tgt *tableMeta) error {
	tc := map[string]colMeta{}
	for _, c := range tgt.Cols {
		tc[strings.ToLower(c.Name)] = c
	}
	for _, c := range src.Cols {
		t, ok := tc[strings.ToLower(c.Name)]
		if !ok {
			return fmt.Errorf("the target has no column %s (enable schema publishing)", c.Name)
		}
		if t.decl() != c.decl() {
			return fmt.Errorf("column %s: %s in the source, %s in the target", c.Name, c.decl(), t.decl())
		}
		// varchar bytes depend on the code page: different collations would hash differently
		if !strings.EqualFold(t.Collation, c.Collation) {
			return fmt.Errorf("column %s: collation %s in the source, %s in the target", c.Name, c.Collation, t.Collation)
		}
	}
	return nil
}

// rawKeyBytes: size of the lossless fixed-size binary form of a key column (rawKeyEnc).
func (c colMeta) rawKeyBytes() (int, bool) {
	switch c.Type {
	case "tinyint", "bit":
		return 1, true
	case "smallint":
		return 2, true
	case "int", "date", "smalldatetime":
		return 4, true
	case "bigint", "datetime":
		return 8, true
	case "uniqueidentifier":
		return 16, true
	case "nchar", "binary":
		return c.MaxLen, c.MaxLen > 0
	case "char":
		return 2 * c.MaxLen, c.MaxLen > 0 // as nchar: lossless from any code page
	}
	return 0, false
}

func (c colMeta) rawKeyEnc(ref string) string {
	n, _ := c.rawKeyBytes()
	switch c.Type {
	case "date":
		return "CAST(DATEDIFF(day, CAST('00010101' AS date), " + ref + ") AS binary(4))"
	case "char":
		return fmt.Sprintf("CAST(CAST(%s AS nchar(%d)) AS binary(%d))", ref, c.MaxLen, n)
	}
	return fmt.Sprintf("CAST(%s AS binary(%d))", ref, n)
}

// rawKeyDec: SQL turning the bytes back into the column value.
func (c colMeta) rawKeyDec(b string) string {
	switch c.Type {
	case "bit":
		return "CAST(CAST(" + b + " AS tinyint) AS bit)"
	case "date":
		return "DATEADD(day, CAST(" + b + " AS int), CAST('00010101' AS date))"
	case "nchar", "char":
		return fmt.Sprintf("CAST(%s AS nchar(%d))", b, c.MaxLen/map[bool]int{true: 2, false: 1}[c.Type == "nchar"])
	case "binary":
		return fmt.Sprintf("CAST(%s AS binary(%d))", b, c.MaxLen)
	}
	return "CAST(" + b + " AS " + c.Type + ")"
}
